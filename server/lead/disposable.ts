/** True for a listed disposable domain or any subdomain of one. */
export const isDisposableDomain = (domain: string): boolean => {
  let d = domain.trim().toLowerCase();
  for (;;) {
    if (DISPOSABLE.has(d)) return true;
    const dot = d.indexOf('.');
    if (dot < 0 || d.indexOf('.', dot + 1) < 0) return false;
    d = d.slice(dot + 1);
  }
};

export const DISPOSABLE_DOMAIN_COUNT = DISPOSABLE.size;
